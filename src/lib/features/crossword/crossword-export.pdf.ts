import type { Color, PDFDocument, PDFFont, PDFPage } from 'pdf-lib';

import type {
	CrosswordPdfMode,
	CrosswordPdfResult
} from '$lib/features/crossword/crossword-export.types';

import {
	CROSSWORD_PDF_MODES,
	type CrosswordGridLetterReveal,
	type CrosswordPdfPageSize
} from '$lib/features/crossword/crossword-pdf-modes';

import { MAX_CROSSWORD_TITLE_LENGTH } from '$lib/features/crossword/crossword.constants';

import type { CrosswordEntry, CrosswordLayout } from '$lib/features/crossword/crossword.types';

import { normalizeAnswer } from '$lib/features/crossword/crossword.utils';

import { createFileTimestamp, triggerBlobDownload } from '$lib/utils/download';

const PAGE_SIZES: Record<CrosswordPdfPageSize, [number, number]> = {
	'a4-portrait': [595.28, 841.89],
	'a3-landscape': [1190.55, 841.89],
	'a3-portrait': [841.89, 1190.55]
};

const GRID_HEADINGS: Record<CrosswordGridLetterReveal, string> = {
	none: 'TTS Kosong',
	'first-letters': 'TTS Awalan',
	all: 'Kunci Jawaban'
};

const TOP_MARGIN = 25;
const SIDE_MARGIN = 15;
const BOTTOM_MARGIN = 30;

/**
 * Batas atas ukuran cell; grid besar otomatis mengecil agar muat di halaman.
 */
const MAX_CELL_SIZE = 32;

/**
 * Cell dibagi zona nomor (atas) dan zona huruf (bawah) dengan gap di
 * antaranya. Font tiap zona hanya mengisi sebagian tinggi zonanya agar
 * nomor dan huruf selalu terpisah secara visual.
 */
const NUMBER_ZONE_HEIGHT_RATIO = 0.38;

const NUMBER_ZONE_FILL_RATIO = 0.72;

const ZONE_GAP_RATIO = 0.03;

const MAX_NUMBER_FONT_SIZE = 16;

/**
 * Hanya pengaman agar shrink-to-fit nomor gabungan (mis. "45/78") tidak
 * menghasilkan font 0/negatif; bukan target keterbacaan.
 */
const MIN_NUMBER_FONT_SIZE = 2;

const MAX_LETTER_FONT_SIZE = 16;

const LETTER_ZONE_FONT_RATIO = 0.72;

const HEADER_FONT_SIZE = 11;

type PdfColors = {
	black: Color;
	white: Color;
	yellow: Color;
	muted: Color;
	border: Color;
};

function toPdfSafeText(value: string): string {
	return value
		.normalize('NFKD')
		.replace(/[\u0300-\u036f]/g, '')
		.replace(/[–—]/g, '-')
		.replace(/[""]/g, '"')
		.replace(/['']/g, "'")
		.replace(/[^\x20-\x7E\xA0-\xFF]/g, '?');
}

function wrapPdfText(text: string, font: PDFFont, fontSize: number, maxWidth: number): string[] {
	const words = toPdfSafeText(text).split(/\s+/).filter(Boolean);

	const lines: string[] = [];

	let currentLine = '';

	for (const word of words) {
		const candidate = currentLine ? `${currentLine} ${word}` : word;

		if (font.widthOfTextAtSize(candidate, fontSize) <= maxWidth) {
			currentLine = candidate;

			continue;
		}

		if (currentLine) {
			lines.push(currentLine);
		}

		currentLine = word;
	}

	if (currentLine) {
		lines.push(currentLine);
	}

	return lines.length > 0 ? lines : [''];
}

type PdfRenderContext = {
	pdfDocument: PDFDocument;
	font: PDFFont;
	boldFont: PDFFont;
	colors: PdfColors;
	crosswordTitle: string;
};

/**
 * Kredit kecil di pojok kanan atas, di atas area konten.
 */
function drawPageCredit(page: PDFPage, { font, colors }: PdfRenderContext): void {
	const text = 'Generated by TTS Generator - wiraananda.vercel.app';
	const { width, height } = page.getSize();
	const textWidth = font.widthOfTextAtSize(text, 8);

	page.drawText(text, {
		x: width - SIDE_MARGIN - textWidth,
		y: height - TOP_MARGIN + 4,
		size: 8,
		font,
		color: colors.muted
	});
}

/**
 * Header satu baris "<heading> | <judul TTS>" (tanpa "|" bila judul kosong).
 * Mengembalikan posisi y untuk konten di bawahnya.
 */
function drawCompactHeaderLine(
	page: PDFPage,
	heading: string,
	startY: number,
	{ boldFont, colors, crosswordTitle }: PdfRenderContext
): number {
	const trimmedTitle = crosswordTitle.trim();

	const headerText = trimmedTitle ? `${heading} | ${trimmedTitle}` : heading;

	const { width } = page.getSize();

	const maxWidth = width - SIDE_MARGIN * 2;

	const headerLines = wrapPdfText(headerText, boldFont, HEADER_FONT_SIZE, maxWidth);

	let y = startY;

	for (const line of headerLines) {
		page.drawText(line, {
			x: SIDE_MARGIN,

			y,

			size: HEADER_FONT_SIZE,

			font: boldFont,

			color: colors.black
		});

		y -= HEADER_FONT_SIZE + 4;
	}

	return y - 4;
}

function drawCrosswordGrid(
	page: PDFPage,
	layout: CrosswordLayout,
	boldFont: PDFFont,
	colors: PdfColors,
	letterReveal: CrosswordGridLetterReveal,
	contentTop: number
): void {
	const { width: pageWidth } = page.getSize();

	const availableWidth = pageWidth - SIDE_MARGIN * 2;
	const availableHeight = contentTop - BOTTOM_MARGIN;

	const cellSize = Math.min(
		MAX_CELL_SIZE,
		availableWidth / layout.width,
		availableHeight / layout.height
	);

	const gridWidth = layout.width * cellSize;
	const gridHeight = layout.height * cellSize;

	const startX = Math.max(SIDE_MARGIN, (pageWidth - gridWidth) / 2);
	const startY = BOTTOM_MARGIN;

	const numberZoneHeight = cellSize * NUMBER_ZONE_HEIGHT_RATIO;
	const zoneGap = Math.max(1, cellSize * ZONE_GAP_RATIO);
	const letterZoneHeight = cellSize - numberZoneHeight - zoneGap;

	const baseNumberFontSize = Math.min(
		MAX_NUMBER_FONT_SIZE,
		numberZoneHeight * NUMBER_ZONE_FILL_RATIO
	);

	const letterFontSize = Math.min(MAX_LETTER_FONT_SIZE, letterZoneHeight * LETTER_ZONE_FONT_RATIO);

	const cellMap = new Map(layout.cells.map((cell) => [`${cell.x}-${cell.y}`, cell]));

	// Render seluruh area grid agar cell kosong menjadi block hitam
	for (let row = 0; row < layout.height; row++) {
		for (let column = 0; column < layout.width; column++) {
			const x = startX + column * cellSize;
			const y = startY + gridHeight - (row + 1) * cellSize;

			const cell = cellMap.get(`${column}-${row}`);

			if (!cell) {
				page.drawRectangle({
					x,
					y,
					width: cellSize,
					height: cellSize,
					color: colors.black
				});

				continue;
			}

			const isStartingCell = Boolean(cell.numbers && cell.numbers.length > 0);

			const isYellowHint = letterReveal === 'first-letters' && isStartingCell;

			page.drawRectangle({
				x,
				y,
				width: cellSize,
				height: cellSize,
				color: isYellowHint ? colors.yellow : colors.white,
				borderWidth: 0.7,
				borderColor: colors.black
			});

			if (isStartingCell) {
				const numberText = cell.numbers!.join('/');

				let numberFontSize = baseNumberFontSize;
				const maxNumberWidth = cellSize - 4;

				while (
					numberFontSize > MIN_NUMBER_FONT_SIZE &&
					boldFont.widthOfTextAtSize(numberText, numberFontSize) > maxNumberWidth
				) {
					numberFontSize -= 0.5;
				}

				page.drawText(numberText, {
					x: x + 2,
					y: y + cellSize - numberFontSize - 1,
					size: numberFontSize,
					font: boldFont,
					color: colors.black
				});
			}

			const shouldRevealLetter =
				letterReveal === 'all' || (letterReveal === 'first-letters' && isStartingCell);

			if (!shouldRevealLetter) {
				continue;
			}

			const letterWidth = boldFont.widthOfTextAtSize(cell.letter, letterFontSize);

			page.drawText(cell.letter, {
				x: x + (cellSize - letterWidth) / 2,
				y: y + (cellSize - letterFontSize) / 2,
				size: letterFontSize,
				font: boldFont,
				color: colors.black
			});
		}
	}
}

function drawGridSection(
	context: PdfRenderContext,
	layout: CrosswordLayout,
	letterReveal: CrosswordGridLetterReveal,
	pageSize: CrosswordPdfPageSize
): void {
	const page = context.pdfDocument.addPage(PAGE_SIZES[pageSize]);

	const contentTop = drawCompactHeaderLine(
		page,
		GRID_HEADINGS[letterReveal],
		page.getHeight() - TOP_MARGIN,
		context
	);

	drawCrosswordGrid(page, layout, context.boldFont, context.colors, letterReveal, contentTop);

	drawPageCredit(page, context);
}

function drawQuestionPages(
	context: PdfRenderContext,
	entries: CrosswordEntry[],
	layout: CrosswordLayout,
	pageSize: CrosswordPdfPageSize
): void {
	const { pdfDocument, boldFont, colors } = context;
	const directionByEntryId = new Map(
		layout.placements.map((placement) => [placement.entryId, placement.direction])
	);

	const activeEntries = entries
		.map((entry, index) => ({
			entry,
			number: index + 1
		}))
		.filter(({ entry }) => normalizeAnswer(entry.answer) !== '');

	let page = pdfDocument.addPage(PAGE_SIZES[pageSize]);

	let y = page.getHeight() - TOP_MARGIN;

	function drawHeader(continued = false): void {
		const heading = continued ? 'Daftar Soal - Lanjutan' : 'Daftar Soal';

		y = drawCompactHeaderLine(page, heading, y, context);
	}

	drawHeader();

	const groupedEntries = {
		across: activeEntries.filter(({ entry }) => directionByEntryId.get(entry.id) === 'across'),
		down: activeEntries.filter(({ entry }) => directionByEntryId.get(entry.id) === 'down')
	};

	for (const [direction, title] of [
		['across', 'MENDATAR'],
		['down', 'MENURUN']
	] as const) {
		const sectionEntries = groupedEntries[direction];

		if (sectionEntries.length === 0) continue;

		if (y - 30 < 40) {
			drawPageCredit(page, context);

			page = pdfDocument.addPage(PAGE_SIZES[pageSize]);

			y = page.getHeight() - TOP_MARGIN;

			drawHeader(true);
		}

		page.drawText(title, {
			x: SIDE_MARGIN,

			y,

			size: 12,

			font: boldFont,

			color: colors.black
		});

		y -= 22;

		for (const { entry, number } of sectionEntries) {
			const text = `${number}. ${entry.clue.trim()}`;

			const lines = wrapPdfText(text, boldFont, 10, page.getWidth() - SIDE_MARGIN * 2);

			const requiredHeight = lines.length * 14 + 8;

			if (y - requiredHeight < 40) {
				drawPageCredit(page, context);

				page = pdfDocument.addPage(PAGE_SIZES[pageSize]);

				y = page.getHeight() - TOP_MARGIN;

				drawHeader(true);
			}

			for (const line of lines) {
				page.drawText(line, {
					x: SIDE_MARGIN,

					y,

					size: 10,

					font: boldFont,

					color: colors.black
				});

				y -= 14;
			}

			y -= 5;
		}

		y -= 28;
	}

	drawPageCredit(page, context);
}

function sanitizePdfFileNameSegment(value: string): string {
	return value
		.replace(/[\\/:*?"<>|]+/g, '-')
		.replace(/\s+/g, ' ')
		.trim()
		.slice(0, MAX_CROSSWORD_TITLE_LENGTH);
}

/**
 * Nama file = judul TTS + suffix mode, atau berbasis timestamp bila judul
 * kosong setelah disanitasi.
 */
function createPdfFileName(crosswordTitle: string, mode: CrosswordPdfMode): string {
	const { fileNameSuffix, timestampSuffix } = CROSSWORD_PDF_MODES[mode];

	const safeTitle = sanitizePdfFileNameSegment(crosswordTitle);

	if (!safeTitle) {
		return `tts-${createFileTimestamp()}${timestampSuffix}.pdf`;
	}

	return `${safeTitle}${fileNameSuffix}.pdf`;
}

/**
 * Halaman yang dibuat ditentukan oleh `CROSSWORD_PDF_MODES[mode].pages`.
 */
export async function generateCrosswordPdfBytes(
	entries: CrosswordEntry[],
	layout: CrosswordLayout,
	crosswordTitle = '',
	mode: CrosswordPdfMode = 'complete'
): Promise<Uint8Array> {
	const { PDFDocument, StandardFonts, rgb } = await import('pdf-lib');

	const pdfDocument = await PDFDocument.create();

	pdfDocument.setTitle(crosswordTitle.trim() || 'TTS Generator');

	pdfDocument.setAuthor('Wiraa');

	const context: PdfRenderContext = {
		pdfDocument,
		font: await pdfDocument.embedFont(StandardFonts.Helvetica),
		boldFont: await pdfDocument.embedFont(StandardFonts.HelveticaBold),
		colors: {
			black: rgb(0, 0, 0),
			white: rgb(1, 1, 1),
			yellow: rgb(1, 1, 0),
			muted: rgb(0.35, 0.35, 0.35),
			border: rgb(0.5, 0.5, 0.5)
		},
		crosswordTitle
	};

	for (const page of CROSSWORD_PDF_MODES[mode].pages) {
		if (page.kind === 'grid') {
			drawGridSection(context, layout, page.reveal, page.size);
		} else {
			drawQuestionPages(context, entries, layout, page.size);
		}
	}

	return pdfDocument.save();
}

export async function downloadCrosswordPdf(
	entries: CrosswordEntry[],
	layout: CrosswordLayout,
	crosswordTitle = '',
	mode: CrosswordPdfMode = 'complete'
): Promise<CrosswordPdfResult> {
	const bytes = await generateCrosswordPdfBytes(entries, layout, crosswordTitle, mode);

	const fileName = createPdfFileName(crosswordTitle, mode);

	const blob = new Blob([bytes as Uint8Array<ArrayBuffer>], {
		type: 'application/pdf'
	});

	triggerBlobDownload(blob, fileName);

	return {
		fileName,
		downloadedAt: new Date().toISOString()
	};
}
